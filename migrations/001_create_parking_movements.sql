
CREATE TABLE IF NOT EXISTS public.parking_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    user_id bigint NOT NULL REFERENCES public."user"(id),
    parking_lot_id bigint NOT NULL REFERENCES public.parking_lots(id),
    event_type text NOT NULL CHECK (event_type IN ('entry', 'exit'))
);

CREATE INDEX IF NOT EXISTS idx_parking_movements_created_at
    ON public.parking_movements (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_parking_movements_user_id
    ON public.parking_movements (user_id);

ALTER TABLE public.parking_movements ENABLE ROW LEVEL SECURITY;
